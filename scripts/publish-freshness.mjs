import fs from "node:fs";
const {broken,inconclusive,checkedAt}=JSON.parse(fs.readFileSync("freshness-report.json","utf8"));
if(!broken.length){console.log("No actionable freshness issues");process.exit(0);}
const repo=process.env.GITHUB_REPOSITORY,token=process.env.GITHUB_TOKEN;
if(!repo||!token)throw Error("GITHUB_REPOSITORY and GITHUB_TOKEN required");
const base="https://api.github.com/repos/"+repo;
const headers={Authorization:"Bearer "+token,Accept:"application/vnd.github+json","X-GitHub-Api-Version":"2022-11-28","Content-Type":"application/json"};
const request=async (endpoint,options={})=>{
 const response=await fetch(base+endpoint,{...options,headers});
 if(!response.ok)throw Error("GitHub API "+response.status+" "+endpoint);
 return response.json();
};
const title="Automated review: broken or archived local-agent evidence";
const line=x=>"- **"+x.agent+"** "+x.type+": "+x.reason+" — "+x.url;
const body=[
 "# Repository evidence freshness report",
 "Checked: "+checkedAt,
 "",
 "An automated scan identified items requiring **human review**. Do not delete agents based solely on this report.",
 "",
 "## Actionable observations",
 ...broken.map(line),
 "",
 "## Inconclusive requests (not evidence of breakage)",
 ...(inconclusive.length?inconclusive.map(line):["- None"]),
 "",
 "Generated by .github/workflows/freshness.yml."
].join("\n");
const issues=await request("/issues?state=open&per_page=100");
const existing=issues.find(issue=>!issue.pull_request&&issue.title===title);
if(!existing){const created=await request("/issues",{method:"POST",body:JSON.stringify({title,body})});console.log("Created issue #"+created.number);}
else if(existing.body!==body){
 await request("/issues/"+existing.number,{method:"PATCH",body:JSON.stringify({body})});
 console.log("Updated issue #"+existing.number);
}else console.log("Issue #"+existing.number+" unchanged");
